/// Referral links + certificate dividends (DECISIONS §71.144).
///
/// The user's own words, 2026-09-19:
///   "Create a referral link under My Account, giving every user an ID (the link must not show the
///    wallet address). When a user who arrives through that link signs in and enters a match, pay
///    the promoter a commission out of the fee."
///
/// 🔴 §71.166 changed where that commission comes from: it is now its own slice of the fee
/// (REFERRAL_SHARE of RAKE_SHARES in `core/uploop/ledger/book.py`), not a cut of the platform's
/// own share, and the part no promoter claims falls to the platform. Because the fee is itself
/// capped by what the losers staked, `rebate_bps` below is a **ceiling**, not a flat rate.
///
/// 🔴 "the link must not show the wallet address" is a hard requirement: what the link carries is
/// an 8-character random code issued by the backend (the `code` in `GET /referral`), with no way
/// to derive an address from it. The frontend must never put `account` into a referral link.
///
/// Timing: **the user is not signed in when they click the link** (most people click the link
/// first, then connect a wallet, then sign). So
///   1. as soon as the page loads, `?ref=` is taken into localStorage and wiped from the address
///      bar (`captureRef`);
///   2. once there really is a session, `POST /referral/bind` is called (`bindPendingRef`).
/// Binding happens **once per lifetime** in the backend, and only counts commission on bets placed
/// after the bind, so retrying here is safe.
import { ApiError, apiGet, apiPost } from "./api";

/// The key the referral code is stored under. localStorage rather than sessionStorage: someone who
/// clicks the link now and connects a wallet two days later still counts.
const KEY = "uploop.ref";
/// The query parameter in the address bar. Short, easy to say, and what everyone else uses.
const PARAM = "ref";

export interface ReferralEarning {
  poolId: number;
  /// Set when the row came from a summit race round or a Daily Arena room (fees split like a match fee)
  race: RaceMatch | null;
  daily: number | null;
  /// In USDT's smallest unit (18 decimals), like every other amount in the ledger
  amount: bigint;
  at: number;
}

export interface Referral {
  /// My referral code (8 characters, generated by the backend, unrelated to the wallet address)
  code: string;
  /// How many people are bound to me
  invited: number;
  /// Total commission; already in the arena balance, with nothing to claim
  earned: bigint;
  /// The **highest** commission rate (basis points), supplied by the backend and never hard-coded
  /// here. A match whose fee was held down by small losses pays proportionally less than this.
  rebateBps: number;
  /// Who referred me: `code` is their referral code. Absent means I arrived directly
  bound: { code: string; at: number } | null;
  /// The most recent commissions. 🔴 Matches and amounts only, **never who entered** — the
  /// backend deliberately does not supply it (that is someone else's privacy)
  recent: ReferralEarning[];
}

interface ReferralJson {
  code: string;
  invited: number;
  earned: string;
  rebate_bps: number;
  bound: { code: string; bound_at: number } | null;
  recent: { pool_id: number; amount: string; at: number; race_room?: number | null; race_round?: number | null; daily_room?: number | null }[];
}

/// Summit race rounds share the match tables under their own pool-id range; the API names the
/// room and round so the UI never has to decode the id.
export interface RaceMatch { room: number; round: number }

function raceOf(x: { race_room?: number | null; race_round?: number | null }): RaceMatch | null {
  return x.race_room ? { room: Number(x.race_room), round: Number(x.race_round || 0) } : null;
}

/// Daily Arena rooms likewise have their own pool-id range; `daily_room` names the room.
function dailyOf(x: { daily_room?: number | null }): number | null {
  return x.daily_room ? Number(x.daily_room) : null;
}

export interface DividendRow {
  poolId: number;
  race: RaceMatch | null;
  daily: number | null;
  /// Which of the two halves of the stakers' share this row is: `all` = the one part shared by
  /// every staked certificate on the site, `win` = the six parts that follow the winning assets
  /// of that match (DIVIDEND_ALL_SHARE / DIVIDEND_WIN_SHARE in `core/uploop/ledger/book.py`)
  scope: "all" | "win";
  /// How many certs this one was computed on
  shares: number;
  amount: bigint;
  paidAt: number | null;
}

export interface Dividends {
  /// Total USDT received (already in the arena balance)
  earned: bigint;
  /// How many matches paid out
  times: number;
  recent: DividendRow[];
}

interface DividendsJson {
  earned: string;
  times: number;
  recent: { pool_id: number; scope: string; shares: number; amount: string; paid_at: number | null; race_room?: number | null; race_round?: number | null; daily_room?: number | null }[];
}

/// Every number the referral card needs. Throws 401 when not signed in (the caller treats that as
/// "sign in first").
export async function loadReferral(): Promise<Referral> {
  const r = await apiGet<ReferralJson>("/referral");
  return {
    code: String(r.code || ""),
    invited: Number(r.invited || 0),
    earned: BigInt(r.earned || "0"),
    rebateBps: Number(r.rebate_bps || 0),
    bound: r.bound ? { code: String(r.bound.code || ""), at: Number(r.bound.bound_at || 0) } : null,
    recent: (r.recent ?? []).map((x) => ({ poolId: Number(x.pool_id), race: raceOf(x), daily: dailyOf(x), amount: BigInt(x.amount || "0"), at: Number(x.at || 0) })),
  };
}

/// How much certificate-staking dividend I have received (both halves of the stakers' share of
/// the fee, §71.144 as re-proportioned by §71.166).
export async function loadDividends(): Promise<Dividends> {
  const d = await apiGet<DividendsJson>("/dividends");
  return {
    earned: BigInt(d.earned || "0"),
    times: Number(d.times || 0),
    recent: (d.recent ?? []).map((x) => ({
      poolId: Number(x.pool_id),
      race: raceOf(x),
      daily: dailyOf(x),
      scope: x.scope === "win" ? "win" : "all",
      shares: Number(x.shares || 0),
      amount: BigInt(x.amount || "0"),
      paidAt: x.paid_at == null ? null : Number(x.paid_at),
    })),
  };
}

/// What my referral link looks like. Built from the current page's address, so local testing, the
/// tunnel and the live site are each correct on their own.
export function refLink(code: string): string {
  const u = new URL(window.location.href);
  u.hash = "";
  u.search = `?${PARAM}=${encodeURIComponent(code)}`;
  return u.toString();
}

/// Whether a referral code is well formed (the backend's alphabet is the 31 upper-case letters and
/// digits left after removing 0/1/O/I/L, length 8).
/// This is only a loose shape check: whether a code is really accepted is the backend's call, and
/// the frontend neither restates the rule nor races to report the error.
function looksLikeCode(s: string): boolean {
  return /^[0-9A-Z]{4,24}$/.test(s);
}

/// Called once as soon as the page loads: take `?ref=xxx` away and **wipe it from the address
/// bar**.
///
/// 🔴 Wiping it is not cosmetic: an address that still carries `?ref=` gets forwarded by the user,
/// pasted into group chats and saved as a bookmark, and after a few hops it becomes "A's link
/// carrying B's code". Take it, then wipe it; the link only works on the first click.
export function captureRef(): void {
  try {
    const u = new URL(window.location.href);
    const raw = (u.searchParams.get(PARAM) || "").trim().toUpperCase();
    if (!raw) return;
    u.searchParams.delete(PARAM);
    window.history.replaceState(null, "", u.pathname + (u.searchParams.toString() ? `?${u.searchParams}` : "") + u.hash);
    if (looksLikeCode(raw)) window.localStorage.setItem(KEY, raw);
  } catch {
    /* localStorage throws in private mode; failing to remember a referral code must not stop the
       whole page from opening */
  }
}

/// The referral code still held and not yet bound (null when there is none).
export function pendingRef(): string | null {
  try {
    const v = (window.localStorage.getItem(KEY) || "").trim();
    return looksLikeCode(v) ? v : null;
  } catch {
    return null;
  }
}

function clearRef(): void {
  try {
    window.localStorage.removeItem(KEY);
  } catch {
    /* as above */
  }
}

/// Called once after signing in: bind the code that was being held.
///
/// Returns whether it bound. 🔴 An error **never raises a dialog**: the user came to play matches,
/// and "that referral code did not work" should not stand in their way.
/// The cases the backend rejects (my own code, already bound to someone else, no such code) are
/// all final, so the local copy is dropped immediately rather than firing a doomed request on
/// every sign-in. Network errors are kept, to be retried at the next sign-in.
export async function bindPendingRef(): Promise<boolean> {
  const code = pendingRef();
  if (!code) return false;
  try {
    await apiPost("/referral/bind", { code });
    clearRef();
    return true;
  } catch (e) {
    if (e instanceof ApiError && e.status >= 400 && e.status < 500 && e.status !== 401) clearRef();
    return false;
  }
}
